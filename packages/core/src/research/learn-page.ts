// Progressive enhancement only: the page is fully readable with scripting disabled, because
// every check-yourself answer lives in a native <details>. The script only adds "reveal all".
const script = `
document.querySelectorAll('[data-reveal-all]').forEach(function(button){
  button.addEventListener('click', function(){
    var open = button.getAttribute('aria-expanded') === 'true';
    document.querySelectorAll('details.check').forEach(function(item){ item.open = !open; });
    button.setAttribute('aria-expanded', String(!open));
    button.textContent = open ? 'Reveal every answer' : 'Hide every answer';
  });
});
`;

/**
 * A self-contained learning page: inline CSS and JS, no network requests of any kind, every
 * claim quoted with a link back to the source it came from. Safe to open outside Dusori.
 */
export function renderLearnPage(synthesis: TopicSynthesis): string {
  const day = synthesis.generatedAt.slice(0, 10);
  const title = escapeHtml(`Learn — ${synthesis.topicTitle}`);
  const body: string[] = [
    '<main>',
    `<p class="mono">Generated by Dusori · ${escapeHtml(day)}</p>`,
    `<h1>${escapeHtml(synthesis.topicTitle)}</h1>`,
    `<p class="lede">Built from ${synthesis.readCount} of ${synthesis.sourceCount} saved sources, quoting ${synthesis.claimCount} passages. Every passage links back to where it came from.</p>`,
  ];

  if (synthesis.claimCount === 0) {
    body.push(
      '<p>Nothing has been read into quotable passages yet. Save a source, run “Read these”, then create this page again.</p>',
      '</main>',
    );
    return page(title, body.join('\n'), false);
  }

  body.push('<h2>Concepts</h2>');
  for (const cluster of synthesis.clusters) {
    body.push(`<h3>${escapeHtml(cluster.heading)}</h3>`);
    if (cluster.sourceCount === 1) {
      body.push(
        `<p class="thin">Only one source supports this so far — treat it as unconfirmed.</p>`,
      );
    }
    for (const claim of cluster.claims.slice(0, 4)) {
      body.push(
        '<blockquote>',
        `<p>${escapeHtml(claim.text)}</p>`,
        `<cite>${sourceLine(claim.sourceTitle, claim.sourceUrl)}${
          claim.heading ? ` · ${escapeHtml(claim.heading)}` : ''
        }</cite>`,
        '</blockquote>',
      );
    }
  }

  if (synthesis.timeline.length >= 3) {
    body.push('<h2>Timeline</h2>', '<ol class="timeline">');
    for (const entry of synthesis.timeline) {
      body.push(`<li><b>${escapeHtml(entry.year)}</b><span>${sourceLine(entry.title, entry.url)}</span></li>`);
    }
    body.push('</ol>');
  }

  const checks = synthesis.clusters.slice(0, 6);
  if (checks.length > 0) {
    body.push(
      '<h2>Check yourself</h2>',
      '<p>No score is kept and nothing is stored. Answer in your head, then reveal the passage.</p>',
      '<button class="reveal" type="button" data-reveal-all aria-expanded="false">Reveal every answer</button>',
    );
    for (const cluster of checks) {
      const claim = cluster.claims[0];
      if (!claim) continue;
      body.push(
        '<details class="check">',
        `<summary>What do your sources say about ${escapeHtml(cluster.heading.toLowerCase())}?</summary>`,
        `<p>“${escapeHtml(claim.text)}”</p>`,
        `<cite>${sourceLine(claim.sourceTitle, claim.sourceUrl)}</cite>`,
        '</details>',
      );
    }
  }

  if (synthesis.openQuestions.length > 0) {
    body.push('<h2>Open questions</h2>', '<ul>');
    for (const question of synthesis.openQuestions) body.push(`<li>${escapeHtml(question)}</li>`);
    body.push('</ul>');
  }

  if (synthesis.missingLenses.length > 0) {
    body.push(
      `<p class="thin">Nothing saved yet from: ${escapeHtml(synthesis.missingLenses.join(', '))}. That is a gap in coverage, not evidence that nothing exists.</p>`,
    );
  }

  body.push(
    '<footer>Dusori grouped and quoted these passages; it did not verify them. Read the sources before relying on any of this. This file is yours — it works offline and needs no network.</footer>',
    '</main>',
  );

  return page(title, body.join('\n'), checks.length > 0);
}

function page(title: string, body: string, withScript: boolean): string {
  return [
    '<!doctype html>',
    '<html lang="en">',
    '<head>',
    '<meta charset="utf-8">',
    '<meta name="viewport" content="width=device-width, initial-scale=1">',
    `<title>${title}</title>`,
    `<style>${styles}</style>`,
    '</head>',
    '<body>',
    body,
    ...(withScript ? [`<script>${script}</script>`] : []),
    '</body>',
    '</html>',
    '',
  ].join('\n');
}
