/**
 * Escapes text for HTML body context. Source text is untrusted data, and this page is written
 * to a file the user may open outside Dusori, where no sanitizer stands between them.
 */
function escapeHtml(value: string): string {
  return value
    .replace(/&/gu, '&amp;')
    .replace(/</gu, '&lt;')
    .replace(/>/gu, '&gt;')
    .replace(/"/gu, '&quot;')
    .replace(/'/gu, '&#39;');
}

/** Only http(s) links survive; anything else (javascript:, data:) becomes plain text. */
function safeHref(url: string | undefined): string | null {
  if (!url) return null;
  try {
    const parsed = new URL(url);
    return parsed.protocol === 'http:' || parsed.protocol === 'https:' ? parsed.toString() : null;
  } catch {
    return null;
  }
}

function sourceLine(title: string, url?: string): string {
  const href = safeHref(url);
  const label = escapeHtml(title);
  return href
    ? `<a href="${escapeHtml(href)}" target="_blank" rel="noreferrer noopener">${label}</a>`
    : label;
}

